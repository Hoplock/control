package north_test

import (
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"

	"github.com/hoplock/control/internal/identity"
)

// THE CONSOLE'S COPY OF THIS ROUTE TABLE (0050). The console calls only the
// routes it names in ui/src/api/routes.ts, and offers each only to a role
// holding its permission (PLAN M2: RBAC is the API's, and the console holds
// no privilege). ui/test/routes.test.ts holds that list against this table
// and against every role — and it reads the table from a file, because a
// browser-side test cannot ask a Go server. This test keeps that file this
// server's: a route added, removed, re-permissioned or a role changed here
// fails it until the file is regenerated, which is one command:
//
//	HOPLOCK_UPDATE_CONSOLE_ROUTES=1 go test ./internal/httpapi/north -run TestTheConsolesRouteTableIsTheServers
const consoleRoutesFile = "../../../ui/test/north-routes.json"

type consoleRoute struct {
	Method     string `json:"method"`
	Pattern    string `json:"pattern"`
	Access     string `json:"access"`
	Permission string `json:"permission"`
}

type consoleRoutes struct {
	Comment string              `json:"comment"`
	Routes  []consoleRoute      `json:"routes"`
	Roles   map[string][]string `json:"roles"`
}

func TestTheConsolesRouteTableIsTheServers(t *testing.T) {
	f := newServer(t)
	table := consoleRoutes{
		Comment: "Generated by TestTheConsolesRouteTableIsTheServers (internal/httpapi/north). Do not edit.",
		Roles:   map[string][]string{},
	}
	for _, r := range f.server.Routes() {
		if r.Provider != "" {
			continue // a host's routes are its own console's (M27)
		}
		table.Routes = append(table.Routes, consoleRoute{
			Method: r.Method, Pattern: r.Pattern, Access: r.Access, Permission: string(r.Permission),
		})
	}
	slices.SortFunc(table.Routes, func(a, b consoleRoute) int {
		if c := strings.Compare(a.Pattern, b.Pattern); c != 0 {
			return c
		}
		return strings.Compare(a.Method, b.Method)
	})
	for _, role := range identity.AllRoles {
		perms := []string{}
		for _, p := range role.Permissions() {
			perms = append(perms, string(p))
		}
		slices.Sort(perms)
		table.Roles[string(role)] = perms
	}
	got, err := json.MarshalIndent(table, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	got = append(got, '\n')
	path := filepath.FromSlash(consoleRoutesFile)
	if os.Getenv("HOPLOCK_UPDATE_CONSOLE_ROUTES") != "" {
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read the console's route table: %v", err)
	}
	if !bytes.Equal(want, got) {
		t.Fatalf("ui/test/north-routes.json is not this server's route table: regenerate it with\n" +
			"  HOPLOCK_UPDATE_CONSOLE_ROUTES=1 go test ./internal/httpapi/north -run TestTheConsolesRouteTableIsTheServers\n" +
			"and run the console's route test (cd ui && npx vitest run test/routes.test.ts)")
	}
}
