// consoleMappingRulesFile is what the console's claim-mapping editor checks
// each typed name against (0068): the server's own patterns and reserved names,
// and, for each field, the code the server refuses it with, so the editor says
// the server's sentence where the operator types. The console builds from it;
// no pattern or reserved name is written by hand there.
const consoleMappingRulesFile = "../../ui/src/screens/claimMappingRules.json"

type consoleMappingRules struct {
	Comment       string            `json:"comment"`
	SchemaVersion int               `json:"schema_version"`
	MaxEntries    int               `json:"max_entries"`
	Patterns      map[string]string `json:"patterns"`
	Reserved      struct {
		Names  []string `json:"names"`
		Prefix string   `json:"prefix"`
	} `json:"reserved"`
	Fields map[string]consoleFieldRule `json:"fields"`
}

// consoleFieldRule is one field of a mapping document: whether the server
// trims it before checking, the code it refuses an empty one with, and, where
// it has one, the pattern it must match and the code for one that does not,
// and the code for a reserved name.
type consoleFieldRule struct {
	Trimmed  bool   `json:"trimmed"`
	Required string `json:"required"`
	Pattern  string `json:"pattern,omitempty"`
	Invalid  string `json:"invalid,omitempty"`
	Reserved string `json:"reserved,omitempty"`
}

// fieldProbe is how the test proves a field's rule against ParseMapping: a
// document with the field set to a value, and the rejection field it must be
// refused at.
type fieldProbe struct {
	document func(value string) string
	field    string
	// valid is a value the field accepts.
	valid string
}

var fieldProbes = map[string]fieldProbe{
	"claim": {
		document: func(v string) string {
			return "schema_version: 1\nclaims:\n  - claim: " + q(v) + "\n    attribute: dept\n"
		},
		field: "claims[0].claim",
		valid: "dept",
	},
	"attribute": {
		document: func(v string) string {
			return "schema_version: 1\nclaims:\n  - claim: dept\n    attribute: " + q(v) + "\n"
		},
		field: "claims[0].attribute",
		valid: "dept",
	},
	"value": {
		document: func(v string) string {
			return "schema_version: 1\nclaims:\n  - claim: dept\n    attribute: dept\n    values: [" + q(v) + "]\n"
		},
		field: "claims[0].values[0]",
		valid: "eng",
	},
	"group_claim": {
		document: func(v string) string { return "schema_version: 1\ngroups:\n  claim: " + q(v) + "\n" },
		field:    "groups.claim",
		valid:    "groups",
	},
	"external": {
		document: func(v string) string {
			return "schema_version: 1\ngroups:\n  claim: groups\n  map:\n    - external: " + q(v) + "\n      group: sre\n"
		},
		field: "groups.map[0].external",
		valid: "SRE",
	},
	"group": {
		document: func(v string) string {
			return "schema_version: 1\ngroups:\n  claim: groups\n  map:\n    - external: SRE\n      group: " + q(v) + "\n"
		},
		field: "groups.map[0].group",
		valid: "sre",
	},
	"directory": {
		document: func(v string) string {
			return "schema_version: 1\ngroups:\n  claim: groups\n  map:\n    - external: SRE\n      directories: [" + q(v) + "]\n      group: sre\n"
		},
		field: "groups.map[0].directories[0]",
		valid: "corp",
	},
}

func q(v string) string {
	b, _ := json.Marshal(v)
	return string(b)
}

// rejectionAt parses a document and returns the code it was refused with at
// field, or "" when it was not refused there.
func rejectionAt(t *testing.T, document, field string) string {
	t.Helper()
	_, err := identity.ParseMapping([]byte(document))
	var rejected *identity.MappingRejected
	if !errors.As(err, &rejected) {
		return ""
	}
	for _, r := range rejected.Rejections {
		if r.Field == field {
			return r.Code
		}
	}
	return ""
}

// The console's editor checks a typed name with the server's own rules, never
// a copy of them (0068). The file it builds from is generated from
// identity.Rules(), and every field's claim about it — the code an empty value
// is refused with, the pattern it must match, the code for a name outside it,
// for a reserved one, and whether the server trims it — is proven here
// against ParseMapping itself, so the file cannot say something the server
// does not do.
func TestTheConsolesMappingRulesAreTheServers(t *testing.T) {
	rules := identity.Rules()
	out := consoleMappingRules{
		Comment:       "Generated by TestTheConsolesMappingRulesAreTheServers (internal/identity). Do not edit.",
		SchemaVersion: rules.SchemaVersion,
		MaxEntries:    rules.MaxEntries,
		Patterns: map[string]string{
			"attribute":        rules.AttributePattern,
			"group":            rules.GroupPattern,
			"directory_source": rules.DirectorySourcePattern,
		},
		Fields: map[string]consoleFieldRule{
			"claim":       {Trimmed: true, Required: identity.RejectMappingClaimEmpty},
			"attribute":   {Trimmed: true, Required: identity.RejectMappingAttributeName, Pattern: "attribute", Invalid: identity.RejectMappingAttributeName, Reserved: identity.RejectMappingReserved},
			"value":       {Trimmed: true, Required: identity.RejectMappingValueEmpty},
			"group_claim": {Trimmed: true, Required: identity.RejectMappingGroupClaim},
			"external":    {Trimmed: true, Required: identity.RejectMappingGroupName},
			"group":       {Trimmed: true, Required: identity.RejectMappingGroupName, Pattern: "group", Invalid: identity.RejectMappingGroupName},
			"directory":   {Required: identity.RejectMappingDirectoryName, Pattern: "directory_source", Invalid: identity.RejectMappingDirectoryName},
		},
	}
	out.Reserved.Names = rules.ReservedAttributes
	out.Reserved.Prefix = rules.ReservedPrefix

	for name, rule := range out.Fields {
		probe, ok := fieldProbes[name]
		if !ok {
			t.Fatalf("field %s has no probe", name)
		}
		if got := rejectionAt(t, probe.document(""), probe.field); got != rule.Required {
			t.Errorf("%s: empty is refused with %q; the file says %q", name, got, rule.Required)
		}
		if got := rejectionAt(t, probe.document(probe.valid), probe.field); got != "" {
			t.Fatalf("%s: %q is refused with %q; the probe's valid value must be accepted", name, probe.valid, got)
		}
		// A trimmed field accepts its valid value padded; one that is not
		// trimmed refuses it.
		if got := rejectionAt(t, probe.document(" "+probe.valid+" "), probe.field); (got == "") != rule.Trimmed {
			t.Errorf("%s: a padded value is refused with %q; the file says trimmed=%t", name, got, rule.Trimmed)
		}
		if rule.Pattern != "" {
			// One name outside the pattern, refused with the file's code.
			if got := rejectionAt(t, probe.document("Not Valid!"), probe.field); got != rule.Invalid {
				t.Errorf("%s: a name outside its pattern is refused with %q; the file says %q", name, got, rule.Invalid)
			}
		}
		if rule.Reserved != "" {
			for _, reserved := range append(slices.Clone(rules.ReservedAttributes), rules.ReservedPrefix+"x") {
				if got := rejectionAt(t, probe.document(reserved), probe.field); got != rule.Reserved {
					t.Errorf("%s: %q is refused with %q; the file says %q", name, reserved, got, rule.Reserved)
				}
			}
		}
	}

	// Each pattern answers as the server's own check does, over names on both
	// sides of every edge each rule has.
	samples := []string{
		"", "a", "A", "0", "-", "a-b", "a_b", "a.b", "a..b", "a.", ".a", "a b", "é", "sre", "SRE",
		"Payments-Engineering", "payments_eng.v2", "hoplock.x", "chain_hop_proxy_id", "corp", "lab-2",
		"-corp", "corp-", "Corp", "x" + strings.Repeat("y", 62), "x" + strings.Repeat("y", 63), "a\nb",
	}
	attribute := regexp.MustCompile(rules.AttributePattern)
	group := regexp.MustCompile(rules.GroupPattern)
	source := regexp.MustCompile(rules.DirectorySourcePattern)
	for _, s := range samples {
		if got, want := attribute.MatchString(s), identity.AttributeProblem(s) != identity.AttributeInvalid; got != want {
			t.Errorf("attribute pattern on %q = %t; AttributeProblem says %t", s, got, want)
		}
		if got, want := source.MatchString(s), identity.DirectorySourceProblem(s) == ""; got != want {
			t.Errorf("source pattern on %q = %t; DirectorySourceProblem says %t", s, got, want)
		}
		groupRefused := rejectionAt(t, fieldProbes["group"].document(s), "groups.map[0].group") != ""
		if got := group.MatchString(strings.TrimSpace(s)); got == groupRefused {
			t.Errorf("group pattern on %q = %t; ParseMapping refused=%t", s, got, groupRefused)
		}
	}

	got, err := json.MarshalIndent(out, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	got = append(got, '\n')
	path := filepath.FromSlash(consoleMappingRulesFile)
	if os.Getenv("HOPLOCK_UPDATE_MAPPING_RULES") != "" {
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read the console's mapping rules: %v", err)
	}
	if !bytes.Equal(want, got) {
		t.Fatalf("ui/src/screens/claimMappingRules.json is not this server's rules: regenerate it with\n" +
			"  HOPLOCK_UPDATE_MAPPING_RULES=1 go test ./internal/identity -run TestTheConsolesMappingRulesAreTheServers\n" +
			"and run the console's editor tests (cd ui && npx vitest run test/claimMappingDocument.test.ts)")
	}
}
