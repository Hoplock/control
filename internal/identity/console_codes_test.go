package identity_test

import (
	"bytes"
	"encoding/json"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
	"testing"
)

// consoleMappingCodesFile is what the console holds its rejection sentences
// to (ui/test/claimMapping.test.ts, 0055): every code a mapping write can be
// refused with.
const consoleMappingCodesFile = "../../ui/test/mapping-codes.json"

type consoleMappingCodes struct {
	Comment string   `json:"comment"`
	Codes   []string `json:"codes"`
}

// The console renders a refused mapping's faults from their codes, never from
// the English beside them (M21), so it must have a sentence for every code.
// The codes are the RejectMapping* constants, read from the source so a new
// one cannot be added without the console's list moving with it.
func TestTheConsolesMappingCodesAreTheServers(t *testing.T) {
	file, err := parser.ParseFile(token.NewFileSet(), "mapping.go", nil, 0)
	if err != nil {
		t.Fatal(err)
	}
	var codes []string
	ast.Inspect(file, func(n ast.Node) bool {
		spec, ok := n.(*ast.ValueSpec)
		if !ok {
			return true
		}
		for i, name := range spec.Names {
			if !strings.HasPrefix(name.Name, "RejectMapping") || i >= len(spec.Values) {
				continue
			}
			if lit, ok := spec.Values[i].(*ast.BasicLit); ok && lit.Kind == token.STRING {
				v, err := strconv.Unquote(lit.Value)
				if err != nil {
					t.Fatal(err)
				}
				codes = append(codes, v)
			}
		}
		return true
	})
	if len(codes) == 0 {
		t.Fatal("no RejectMapping* constant found in mapping.go")
	}
	slices.Sort(codes)
	got, err := json.MarshalIndent(consoleMappingCodes{
		Comment: "Generated by TestTheConsolesMappingCodesAreTheServers (internal/identity). Do not edit.",
		Codes:   codes,
	}, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	got = append(got, '\n')
	path := filepath.FromSlash(consoleMappingCodesFile)
	if os.Getenv("HOPLOCK_UPDATE_MAPPING_CODES") != "" {
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read the console's mapping codes: %v", err)
	}
	if !bytes.Equal(want, got) {
		t.Fatalf("ui/test/mapping-codes.json is not this server's codes: regenerate it with\n" +
			"  HOPLOCK_UPDATE_MAPPING_CODES=1 go test ./internal/identity -run TestTheConsolesMappingCodesAreTheServers\n" +
			"and give every new code a sentence in the console (cd ui && npx vitest run test/claimMapping.test.ts)")
	}
}
