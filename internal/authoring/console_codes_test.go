package authoring_test

import (
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
	"slices"
	"testing"

	"github.com/hoplock/control/internal/authoring"
	"github.com/hoplock/control/internal/policy/model"
)

// THE CONSOLE'S COPY OF THE POLICY CODES (0053; PLAN M21). The console renders
// a compiler rejection and a publish-time finding from its code and its
// parameters, never from the English beside them, so it needs a sentence for
// every code this server can answer. ui/test/policy.test.ts holds the
// console's catalogue against this list — every code has a sentence, and each
// sentence names only parameters the code carries — and it reads the list from
// a file, because a browser-side test cannot ask a Go package. This test keeps
// that file this server's: a code added, removed or given other parameters
// fails it until the file is regenerated, which is one command:
//
//	HOPLOCK_UPDATE_POLICY_CODES=1 go test ./internal/authoring -run TestTheConsolesPolicyCodesAreTheServers
const consolePolicyCodesFile = "../../ui/test/policy-codes.json"

type consolePolicyCodes struct {
	Comment string `json:"comment"`
	// Rejections are the compiler's codes, and this package's one, each with
	// the parameters its message is filled from.
	Rejections map[string][]string `json:"rejections"`
	// Findings are Control's own publish-time codes. A registered validator's
	// are its provider's, and the console renders them by the fallback.
	Findings []string `json:"findings"`
	// Severities are a finding's three.
	Severities []string `json:"severities"`
}

func TestTheConsolesPolicyCodesAreTheServers(t *testing.T) {
	codes := consolePolicyCodes{
		Comment:    "Generated by TestTheConsolesPolicyCodesAreTheServers (internal/authoring). Do not edit.",
		Rejections: map[string][]string{},
		Findings:   slices.Sorted(slices.Values(authoring.ControlCodes)),
		Severities: []string{authoring.SeverityAdvice, authoring.SeverityWarning, authoring.SeverityBlocking},
	}
	for _, c := range model.Codes() {
		params := model.Parameters(c)
		if params == nil {
			params = []string{}
		}
		codes.Rejections[string(c)] = params
	}
	// The tenant a bundle names against the tenant it was sent to (service.go).
	codes.Rejections[authoring.CodeTenantMismatch] = []string{"bundle", "tenant"}

	got, err := json.MarshalIndent(codes, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	got = append(got, '\n')
	path := filepath.FromSlash(consolePolicyCodesFile)
	if os.Getenv("HOPLOCK_UPDATE_POLICY_CODES") != "" {
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read the console's policy codes: %v", err)
	}
	if !bytes.Equal(want, got) {
		t.Fatalf("ui/test/policy-codes.json is not this server's codes: regenerate it with\n" +
			"  HOPLOCK_UPDATE_POLICY_CODES=1 go test ./internal/authoring -run TestTheConsolesPolicyCodesAreTheServers\n" +
			"and give every new code a sentence in the console (cd ui && npx vitest run test/policy.test.ts)")
	}
}
