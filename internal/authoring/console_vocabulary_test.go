// THE CONSOLE'S COPY OF THE POLICY VOCABULARY (0066; PLAN M3). The visual
// policy editor offers every enumerated field — an effect, an intent, a
// channel type, a rung, an obligation, a cache-key component — as a choice,
// and the choices are this server's, never a list typed into the console. The
// console builds from a file, because a browser bundle cannot ask a Go
// package; this test keeps that file this server's kinds. A member added to a
// kind, or a kind added, fails it until the file is regenerated, which is one
// command:
//
//	HOPLOCK_UPDATE_POLICY_VOCABULARY=1 go test ./internal/authoring -run TestTheConsolesPolicyVocabularyIsTheServers
const consolePolicyVocabularyFile = "../../ui/src/screens/policyVocabulary.json"

type consolePolicyVocabulary struct {
	Comment string `json:"comment"`
	// Vocabularies are model.Vocabularies(): each closed vocabulary by its
	// identifier (the one a refused value names, 0065), its members in the
	// order the kind declares them.
	Vocabularies map[string][]string `json:"vocabularies"`
	// MatchAxes are a rule's five match axes, in the order a match is read.
	MatchAxes []string `json:"match_axes"`
}

func TestTheConsolesPolicyVocabularyIsTheServers(t *testing.T) {
	v := consolePolicyVocabulary{
		Comment:      "Generated by TestTheConsolesPolicyVocabularyIsTheServers (internal/authoring) from internal/policy/model's kinds. Do not edit.",
		Vocabularies: map[string][]string{},
		MatchAxes:    model.MatchAxes(),
	}
	for name, members := range model.Vocabularies() {
		v.Vocabularies[string(name)] = members
	}
	got, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	got = append(got, '\n')
	path := filepath.FromSlash(consolePolicyVocabularyFile)
	if os.Getenv("HOPLOCK_UPDATE_POLICY_VOCABULARY") != "" {
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read the console's policy vocabulary: %v", err)
	}
	if !bytes.Equal(want, got) {
		t.Fatalf("ui/src/screens/policyVocabulary.json is not this server's vocabulary: regenerate it with\n" +
			"  HOPLOCK_UPDATE_POLICY_VOCABULARY=1 go test ./internal/authoring -run TestTheConsolesPolicyVocabularyIsTheServers\n" +
			"and rebuild the console (cd ui && npm run build)")
	}
}

// THE VISUAL EDITOR'S ROUND-TRIP CORPUS IS A REAL BUNDLE, AND IT IS WHOLE
// (0066). ui/test/policyDocument.test.ts round-trips ui/test/policy-corpus.yaml
// through the console's document model, byte for byte; that proves something
// only if the corpus is a bundle this server compiles and it uses every key
// of the schema. This test holds both: it compiles the corpus, and it walks
// the schema's yaml keys — every key of every type a bundle is decoded into,
// read from the model's own types, so a key added to the schema fails here
// until the corpus uses it too.
const consolePolicyCorpusFile = "../../ui/test/policy-corpus.yaml"

func TestTheConsolesPolicyCorpusCompiles(t *testing.T) {
	src, err := os.ReadFile(filepath.FromSlash(consolePolicyCorpusFile))
	if err != nil {
		t.Fatal(err)
	}
	b, err := model.Parse(src)
	if err != nil {
		t.Fatalf("the corpus does not parse: %v", err)
	}
	if rs := b.Validate(); len(rs) > 0 {
		t.Fatalf("the corpus is refused: %v", rs)
	}
	if _, err := compile.Compile(b); err != nil {
		t.Fatalf("the corpus does not compile: %v", err)
	}

	want := map[string]bool{}
	schemaKeys(reflect.TypeFor[model.Bundle](), want, map[reflect.Type]bool{})
	var doc yaml.Node
	if err := yaml.Unmarshal(src, &doc); err != nil {
		t.Fatal(err)
	}
	used := map[string]bool{}
	sourceKeys(doc.Content[0], reflect.TypeFor[model.Bundle](), used)
	for _, k := range slices.Sorted(maps.Keys(want)) {
		if !used[k] {
			t.Errorf("the corpus never uses %s: add it to %s", k, consolePolicyCorpusFile)
		}
	}
}

// Keys with their own decoder, which the walk cannot read from fields.
var decodedKeys = map[reflect.Type][]string{
	reflect.TypeFor[model.Username]():   {"from"},
	reflect.TypeFor[model.TimeWindow](): {},
	reflect.TypeFor[model.Duration]():   {},
}

func elem(t reflect.Type) reflect.Type {
	for t.Kind() == reflect.Pointer || t.Kind() == reflect.Slice {
		t = t.Elem()
	}
	return t
}

// A key is named by the type it belongs to: `Destination.port_range` is one
// key wherever a destination is written.
func keyName(t reflect.Type, k string) string { return t.Name() + "." + k }

func schemaKeys(t reflect.Type, out map[string]bool, seen map[reflect.Type]bool) {
	t = elem(t)
	if seen[t] {
		return
	}
	seen[t] = true
	if keys, ok := decodedKeys[t]; ok {
		for _, k := range keys {
			out[keyName(t, k)] = true
		}
		return
	}
	switch t.Kind() { //nolint:exhaustive // only containers have keys beneath them
	case reflect.Map:
		schemaKeys(t.Elem(), out, seen)
	case reflect.Struct:
		for f := range t.Fields() {
			name, _, _ := strings.Cut(f.Tag.Get("yaml"), ",")
			if name == "" || name == "-" || !f.IsExported() {
				continue
			}
			out[keyName(t, name)] = true
			schemaKeys(f.Type, out, seen)
		}
	}
}

func sourceKeys(n *yaml.Node, t reflect.Type, out map[string]bool) {
	t = elem(t)
	switch n.Kind { //nolint:exhaustive // scalars and aliases have no keys
	case yaml.SequenceNode:
		for _, c := range n.Content {
			sourceKeys(c, t, out)
		}
	case yaml.MappingNode:
		for i := 0; i+1 < len(n.Content); i += 2 {
			k, v := n.Content[i].Value, n.Content[i+1]
			if _, ok := decodedKeys[t]; ok {
				out[keyName(t, k)] = true
				continue
			}
			switch t.Kind() { //nolint:exhaustive // only containers have keys beneath them
			case reflect.Map:
				sourceKeys(v, t.Elem(), out)
			case reflect.Struct:
				for f := range t.Fields() {
					if name, _, _ := strings.Cut(f.Tag.Get("yaml"), ","); name == k {
						out[keyName(t, name)] = true
						sourceKeys(v, f.Type, out)
					}
				}
			}
		}
	}
}
